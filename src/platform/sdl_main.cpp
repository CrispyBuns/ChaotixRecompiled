// Every face and shoulder button is taken by the emulated 6-button pad (and
// Back is its Mode button), so the menu is on the left stick click, which
// nothing else uses. While the menu is open it drives the menu, not the game.
// Back to the title screen. The game has no way there itself, so the copy
// taken when we handed over is put back. That copy carries pointers into the
// machine it came from, so the buses are re-pointed afterwards.
bool return_to_title(App& app) {
    if (!app.title_snapshot) return false;
    *app.m = *app.title_snapshot;
    // The Start handed over at START GAME may still be in flight; leaving it
    // running would walk the game straight back out of the title.
    app.inject_start = 0;
    // A stage asked for but not yet started would fire on the way back in,
    // and its Start taps would go on pressing.
    app.m->stage_pending = false;
    app.stage_kick = -1;
    app.ta.cancel();
    app.m->remap_m68k();
    app.m->remap_sh2();
    app.handed_over = false;
    return true;
}

// Escape, and the pad button standing in for it. Before the game has been
// handed control this is the front end; afterwards it is the pause menu.
void menu_back(App& app) {
    if (app.menu.open()) { app.menu.close(); return; }
    if (app.handed_over) app.menu.toggle(); else app.menu.open_front();
}

// Escape's counterpart on a controller. Which button that is comes from the
// settings (CONTROLS -> MENU BUTTON); the left stick click stands in when the
// name there is not one SDL knows.
SDL_GamepadButton menu_pad_button(const App& app) {
    const SDL_GamepadButton b = SDL_GetGamepadButtonFromString(app.cfg.menu_button.c_str());
    return b == SDL_GAMEPAD_BUTTON_INVALID ? SDL_GAMEPAD_BUTTON_LEFT_STICK : b;
}

// A stage the front end asked for is taken at the game's mode dispatcher, and
// the title screen only gets back there once it is done with itself: one press
// of Start gets past its animation, another leaves it. So Start is tapped
// until the request is taken -- without this the stage waits out the whole
// title screen, about eight seconds of PUSH START.
uint16_t stage_kick_button(App& app) {
    if (app.stage_kick < 0) return 0;
    if (!app.m->stage_pending) {
        app.stage_kick = -1;   // taken: stop at once, or Start would pause the level
        return 0;
    }
    if (app.stage_kick > 900) {
        // Some scene the request cannot interrupt. Leave it waiting rather
        // than hold Start down on the game for ever.
        LOGW("stage", "the game has not come back to its mode dispatcher; the stage is still waiting");
        app.stage_kick = -1;
        return 0;
    }
    // Taps, not a hold: the title screen wants separate presses.
    const bool down = app.stage_kick % 24 < 6;
    ++app.stage_kick;
    return down ? uint16_t(PAD_START) : uint16_t(0);
}

// Watches a time attack run; called once per emulated frame. The game just
// moves the player on when a run ends, so the frontend takes the time and puts
// itself back instead, which is where the player came from.
// Issue #20: the cheats switched on, set before each frame.
void apply_cheats(App& app) {
    std::vector<cheats::Write> writes;
    for (const auto& c : cheats::builtin())
        if (app.cfg.cheats.count(c.key)) writes.insert(writes.end(), c.writes.begin(), c.writes.end());
    if (!app.cfg.cheat_codes.empty()) cheats::parse_codes(app.cfg.cheat_codes, writes);
    app.cheating = !writes.empty();
    if (app.cheating && app.ta.running) app.ta_cheated = true;
    cheats::apply(*app.m, writes);
}

// Settings and the cartridge save, written now. Android ends an app without
// a quit event when it is swiped away, so waiting for the exit lost every
// setting there (issue #26): this runs whenever the menu closes and whenever
// the app goes to the background.
void save_now(App& app) {
    if (app.autotest_frames) return;  // autotests are hermetic
    if (app.m->sram_dirty) app.store.store_sram(*app.m);
    if (!app.cfg.save(app.store.config_file()))
        LOGW("app", "cannot save settings to %s", app.store.config_file().c_str());
}

void follow_time_attack(App& app) {
    if (!app.ta.update(*app.m)) return;
    const int frames = app.ta.time;
    const bool ran_out = app.ta.timed_out();
    const bool timed = app.ta.timed() && !ran_out;
    const bool cheated = app.ta_cheated;
    const bool best = timed && !cheated && record_best(app.cfg, app.ta.request.place,
                                                       app.ta.request.level, frames);
    // Straight to disk, the way an unlocked achievement is. Waiting for a
    // clean exit loses the record if the program does not get one.
    if (best) app.cfg.save(app.store.config_file());
    LOGI("stage", "time attack: over after %d frames%s", frames,
         ran_out ? " (the level's own limit)" : best ? " - a new best" : "");
    const std::string title = ran_out    ? std::string("OUT OF TIME")
                              : !timed   ? std::string("NO TIME")
                                         : "TIME " + stage_select::format_time(frames);
    const std::string note = ran_out  ? "The level's own limit ran out."
                             : !timed ? "This level does not keep a clock."
                             : cheated ? "Cheats were on: not recorded."
                             : best   ? "A new best for this stage."
                                      : "Not a new best.";
    app.toasts.push_back({title, note, SDL_GetTicks() + 6000});
    // The run, as it was played. A recorded time that disagrees with what the
    // game showed can then be looked into without anyone having had to set up
    // a recording beforehand.
    write_recording(app, app.store.save_dir() + "last_run.txt", frames);
    if (return_to_title(app)) app.menu.show_page("timeattack");
}

void handle_pad_button(App& app, Uint8 button) {
    if (app.menu.on_pad(button)) return;
    if (SDL_GamepadButton(button) == menu_pad_button(app)) menu_back(app);
}

void handle_key(App& app, const SDL_KeyboardEvent& k) {
    if (k.repeat) return;
    // An open menu owns the keyboard, so the function keys below cannot be
    // triggered from underneath it.
    if (app.menu.on_key(k.key)) return;
    switch (k.key) {
    case SDLK_ESCAPE: menu_back(app); break;
    case SDLK_F1: app.cfg.debug_overlay = !app.cfg.debug_overlay; break;
    case SDLK_F2: {
        static const AspectMode order[] = {AspectMode::Auto, AspectMode::R4_3, AspectMode::R16_9, AspectMode::R16_10, AspectMode::R21_9};
        int i = 0;
        for (int j = 0; j < 5; ++j) if (order[j] == app.cfg.viewport.aspect) i = j;
        app.cfg.viewport.aspect = order[(i + 1) % 5];
        break;
    }
    case SDLK_F3:
        app.cfg.linear_filter = !app.cfg.linear_filter;
        SDL_SetTextureScaleMode(app.texture, app.cfg.linear_filter ? SDL_SCALEMODE_LINEAR : SDL_SCALEMODE_NEAREST);
        break;
    case SDLK_F4:
        app.cfg.viewport.scale = app.cfg.viewport.scale == ScaleMode::Fit ? ScaleMode::Integer
                               : app.cfg.viewport.scale == ScaleMode::Integer ? ScaleMode::Stretch : ScaleMode::Fit;
        break;
    case SDLK_F5: app.overlay_page = (app.overlay_page + 1) % 4; break;
    case SDLK_F6: app.cfg.widescreen = !app.cfg.widescreen; break;
    case SDLK_F7: app.menu.show_achievements(); break;
    case SDLK_F11:
        app.cfg.window_mode = app.cfg.window_mode == WindowMode::Windowed ? WindowMode::Borderless : WindowMode::Windowed;
        apply_window_mode(app);
        break;
    case SDLK_RETURN:
        if (k.mod & SDL_KMOD_ALT) {
            app.cfg.window_mode = app.cfg.window_mode == WindowMode::Windowed ? WindowMode::Borderless : WindowMode::Windowed;
            apply_window_mode(app);
        }
        break;
    case SDLK_F12: save_screenshot(app); break;
    default: break;
    }
}

