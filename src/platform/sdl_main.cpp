int main(int argc, char** argv) {
    App app;
    // The game image is 4:3 or wider: ask mobile platforms for landscape.
    SDL_SetHint(SDL_HINT_ORIENTATIONS, "LandscapeLeft LandscapeRight");
    if (!SDL_Init(SDL_INIT_VIDEO | SDL_INIT_GAMEPAD | SDL_INIT_AUDIO)) {
        std::fprintf(stderr, "SDL_Init failed: %s\n", SDL_GetError());
        return 1;
    }
    // --user-dir puts settings, saves and the installed ROM in a folder of the
    // caller's choice (portable installs, and the setup test).
    std::string user_dir;
    std::string install_path;  // --install: install this ROM and exit
    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "--user-dir" && i + 1 < argc) user_dir = argv[++i];
        else if (a == "--install" && i + 1 < argc) install_path = argv[++i];
    }
    if (!user_dir.empty() && user_dir.back() != '/' && user_dir.back() != '\\') user_dir += '/';
    if (user_dir.empty()) {
        char* pref = SDL_GetPrefPath("ChaotixRecompiled", "ChaotixRecompiled");
        user_dir = pref ? pref : "./";
        SDL_free(pref);
    } else {
        std::error_code ec;
        std::filesystem::create_directories(user_dir, ec);
    }
    app.store = SaveStore(user_dir);
    if (!app.cfg.load(app.store.config_file())) {
        app.cfg.set_defaults();
        app.cfg.save(app.store.config_file());
    }
    // Non-interactive install: verify and copy the ROM, then exit. Used by
    // packaging scripts and by the setup test.
    if (!install_path.empty()) {
        std::string installed, err;
        if (!install_rom_file(install_path, app.store.root(), &installed, &err)) {
            std::fprintf(stderr, "install failed: %s\n", err.c_str());
            SDL_Quit();
            return 1;
        }
        Rom rom;
        rom.load(installed, &err);
        app.cfg.installed = true;
        app.cfg.rom_sha1 = rom.sha1;
        app.cfg.rom_path = installed;
        app.cfg.save(app.store.config_file());
        std::printf("installed %s (%s)\n", installed.c_str(), rom.sha1.c_str());
        SDL_Quit();
        return 0;
    }

    bool force_interp = false;
    std::string menu_page;
    for (int i = 1; i < argc; ++i) {
        std::string a = argv[i];
        if (a == "--interp") force_interp = true;
        else if (a == "--fullscreen") app.cfg.window_mode = WindowMode::Fullscreen;
        else if (a == "--borderless") app.cfg.window_mode = WindowMode::Borderless;
        else if (a == "--windowed") app.cfg.window_mode = WindowMode::Windowed;
        else if (a == "--aspect" && i + 1 < argc) parse_aspect(argv[++i], app.cfg.viewport.aspect, app.cfg.viewport.custom_aspect);
        else if (a == "--no-widescreen") app.cfg.widescreen = false;
        else if (a == "--user-dir" && i + 1 < argc) ++i;  // handled above
        else if (a == "--touch") app.cfg.touch = TouchMode::On;
        else if (a == "--debug") app.cfg.debug_overlay = true;
        else if (a == "--autotest" && i + 1 < argc) app.autotest_frames = std::strtoull(argv[++i], nullptr, 10);
        else if (a == "--autotest-shot" && i + 1 < argc) app.autotest_shot = argv[++i];
        else if (a == "--mods-dir" && i + 1 < argc) app.mods_dir = argv[++i];
        // Opens a menu page straight away, so it can be captured without a
        // keyboard (the same reason --autotest exists).
        else if (a == "--menu" && i + 1 < argc) menu_page = argv[++i];
        else if (a == "--keys" && i + 1 < argc) {
            // FRAME:KEYNAME[,FRAME:KEYNAME...]
            std::string spec = argv[++i];
            for (size_t st = 0; st < spec.size();) {
                size_t comma = spec.find(',', st);
                std::string one = spec.substr(st, comma == std::string::npos ? comma : comma - st);
                size_t colon = one.find(':');
                if (colon != std::string::npos) {
                    const SDL_Keycode k = SDL_GetKeyFromName(one.substr(colon + 1).c_str());
                    if (k == SDLK_UNKNOWN)
                        std::fprintf(stderr, "--keys: unknown key '%s'\n",
                                     one.substr(colon + 1).c_str());
                    else
                        app.key_script.push_back({std::strtoull(one.c_str(), nullptr, 10), k, false});
                }
                if (comma == std::string::npos) break;
                st = comma + 1;
            }
        }
        else if (a == "--shots" && i + 1 < argc) {
            // FRAME:FILE[,FRAME:FILE...]
            std::string spec = argv[++i];
            for (size_t st = 0; st < spec.size();) {
                size_t comma = spec.find(',', st);
                std::string one = spec.substr(st, comma == std::string::npos ? comma : comma - st);
                size_t colon = one.find(':');
                if (colon != std::string::npos)
                    app.extra_shots.push_back({std::strtoull(one.c_str(), nullptr, 10), one.substr(colon + 1), false});
                if (comma == std::string::npos) break;
                st = comma + 1;
            }
        }
        else if (a == "--record-input" && i + 1 < argc) app.record_path = argv[++i];
        else if (a == "--show-achievements") menu_page = "awards";
        else if (a == "--window-size" && i + 1 < argc) {
            int w = 0, h = 0;
            if (std::sscanf(argv[++i], "%dx%d", &w, &h) == 2) { app.cfg.raw["cli.w"] = std::to_string(w); app.cfg.raw["cli.h"] = std::to_string(h); }
        } else if (a == "--stage" && i + 1 < argc) {
            unsigned f = 0, pl = 0, lv = 0, tm = 0, pc = 0, cc = 0, two = 0;
            if (std::sscanf(argv[++i], "%u:%u:%u:%u:%u:%u:%u", &f, &pl, &lv, &tm, &pc, &cc, &two) == 7) {
                app.cli_stage_frame = std::max(1u, f);
                app.cli_stage.place = uint16_t(pl);
                app.cli_stage.level = uint16_t(lv);
                app.cli_stage.attime = uint16_t(tm);
                app.cli_stage.player = uint16_t(pc);
                app.cli_stage.combi = uint16_t(cc);
                app.cli_stage.two_players = two != 0;
            }
        } else if (a == "--log-timing") {
            app.log_timing = true;
        } else if ((a == "--press" || a == "--hold") && i + 1 < argc) {
            const bool host = a == "--hold";
            // FRAME:BUTTON[+BUTTON]:DURATION
            std::string spec = argv[++i];
            App::Press p{0, 4, 0};
            size_t c1 = spec.find(':'), c2 = spec.find(':', c1 + 1);
            p.frame = std::strtoull(spec.substr(0, c1).c_str(), nullptr, 10);
            std::string names = spec.substr(c1 + 1, c2 == std::string::npos ? std::string::npos : c2 - c1 - 1);
            if (c2 != std::string::npos) p.duration = std::strtoull(spec.substr(c2 + 1).c_str(), nullptr, 10);
            size_t st = 0;
            for (;;) {
                size_t plus = names.find('+', st);
                p.buttons |= pad_button_from_name(names.substr(st, plus == std::string::npos ? std::string::npos : plus - st).c_str());
                if (plus == std::string::npos) break;
                st = plus + 1;
            }
            if (host) app.host_script.push_back({p.frame, p.buttons, int(p.duration), false});
            else app.script.push_back(p);
        }
    }

    int win_h = kActiveLines * app.cfg.window_scale;
    int win_w = int(std::lround(win_h * 4.0 / 3.0));
    if (app.cfg.raw.count("cli.w")) { win_w = std::atoi(app.cfg.raw["cli.w"].c_str()); win_h = std::atoi(app.cfg.raw["cli.h"].c_str()); }
    app.window = SDL_CreateWindow("Knuckles' Chaotix Recompiled", win_w, win_h, SDL_WINDOW_RESIZABLE | SDL_WINDOW_HIGH_PIXEL_DENSITY);
    if (!app.window) { std::fprintf(stderr, "SDL_CreateWindow: %s\n", SDL_GetError()); return 1; }
    if (SDL_Surface* icon = SDL_CreateSurfaceFrom(64, 64, SDL_PIXELFORMAT_RGBA32,
                                                  const_cast<unsigned char*>(app_icon_rgba), 64 * 4)) {
        SDL_SetWindowIcon(app.window, icon);
        SDL_DestroySurface(icon);
    }
    app.renderer = SDL_CreateRenderer(app.window, nullptr);
    if (!app.renderer) { std::fprintf(stderr, "SDL_CreateRenderer: %s\n", SDL_GetError()); return 1; }
    SDL_SetRenderVSync(app.renderer, app.cfg.vsync ? 1 : 0);
    LOGI("app", "renderer: %s", SDL_GetRendererName(app.renderer));
    if (!app.ui.init(app.renderer)) LOGW("app", "no UI font; the menu is unavailable");
    app.menu.bind(app.cfg);
    {
        // Set field by field: a positional list silently shifts every hook
        // along when one is added in the middle.
        Menu::Hooks hooks;
        hooks.apply_video = [&app] {
            SDL_SetRenderVSync(app.renderer, app.cfg.vsync ? 1 : 0);
            if (app.texture)
                SDL_SetTextureScaleMode(app.texture, app.cfg.linear_filter ? SDL_SCALEMODE_LINEAR
                                                                           : SDL_SCALEMODE_NEAREST);
            apply_window_mode(app);
        };
        hooks.quit = [&app] { app.running = false; };
        hooks.start_game = [&app] {
            // Keep the title screen so BACK TO TITLE can return to it, then
            // give the game the Start it is waiting for: it proceeds into its
            // own menus exactly as it would have without us in the way.
            if (!app.title_snapshot) app.title_snapshot = std::make_unique<Machine>();
            *app.title_snapshot = *app.m;
            app.handed_over = true;
            app.inject_start = 8;
        };
        hooks.start_stage = [&app](const stage_select::Request& r) {
            // Same hand-over as START GAME, but from the title screen rather
            // than wherever the game happens to be: the request is applied at
            // the game's mode dispatcher, which a running level never reaches.
            if (app.handed_over) return_to_title(app);
            if (!app.title_snapshot) app.title_snapshot = std::make_unique<Machine>();
            *app.title_snapshot = *app.m;
            app.m->stage_request = r;
            app.m->stage_pending = true;
            app.handed_over = true;
            // Tapping Start until the request is taken, rather than one press:
            // a single one only gets the title past its own animation, and the
            // stage would then wait out the whole title screen (about eight
            // seconds of PUSH START) before the game came back to the
            // dispatcher on its own.
            app.inject_start = 0;
            app.stage_kick = 0;
            app.ta.begin(r);
            app.ta_cheated = false;
            app.recorded_stages.push_back({app.m->frame_count, r, app.m->wide_extra,
                                           app.m->wide_extra_bottom, app.cfg.six_button});
        };
        hooks.back_to_title = [&app] {
            if (return_to_title(app)) app.menu.open_front();
        };
        hooks.front_closed = [&app] {
            // Playing on from the game's own title screen hands it control as
            // much as START GAME does, only without pressing Start for the
            // player: Escape later opens the pause menu, and BACK TO TITLE has
            // a title to return to.
            if (app.handed_over || !app.m) {
                return;
            }
            if (!app.title_snapshot) {
                app.title_snapshot = std::make_unique<Machine>();
            }
            *app.title_snapshot = *app.m;
            app.handed_over = true;
        };
        hooks.pad_count = [&app] { return int(app.pads.size()); };
#ifdef SDL_PLATFORM_ANDROID
        hooks.mods_folder = [] { return android_shared_storage() ? android_shared_mods_dir() : std::string(); };
        hooks.share_mods_folder = [] { android_request_shared_storage(); };
#endif
        hooks.pad_name = [&app](int i) -> std::string {
            if (i < 0 || size_t(i) >= app.pads.size()) return "";
            const char* n = SDL_GetGamepadName(app.pads[size_t(i)]);
            return n ? n : "";
        };
        hooks.reset_awards = [&app] {
            app.achievements.reset_progress();
            std::error_code ec;
            std::filesystem::remove(achievements_progress_path(app), ec);
        };
        app.start_stage = hooks.start_stage;
        app.menu.set_hooks(std::move(hooks));
    }
    // The menu is the front end, so it is up from the start: the game boots
    // behind it and its title screen and attract demo are the backdrop.
    app.menu.open_front();
    if (!menu_page.empty() && !app.menu.show_page(menu_page))
        LOGW("app", "--menu: unknown page '%s' (front, main, options, video, sound, input, extras, controls, cheats, awards)",
             menu_page.c_str());

    // An explicit ROM (including an Explorer drop onto the EXE) is installed
    // once, so subsequent launches use that copy even if the source moves.
    const std::string installed = setup::installed_rom_path(app.store.root());
    std::string rom_path = rom_from_args(argc, argv);
    std::error_code rom_ec;
    if (rom_path.empty() && std::filesystem::exists(installed, rom_ec)) rom_path = installed;
    if (rom_path.empty()) rom_path = app.cfg.rom_path;

    std::string err;
    // Avoid rewriting a verified installed copy on every launch. Old builds
    // accepted unknown images; those must return to setup instead of booting.
    bool ready = rom_path == installed && setup::is_installed(app.store.root(), "");
    if (!ready && !rom_path.empty()) {
        std::string imported;
        ready = install_rom_file(rom_path, app.store.root(), &imported, &err);
        if (ready) rom_path = imported;
    }
    if (!ready) {
        if (app.autotest_frames) {  // tests never show the setup screen
            std::fprintf(stderr, "no usable ROM: %s\n", err.c_str());
            SDL_Quit();
            return 1;
        }
        rom_path = run_setup_screen(app.window, app.renderer, app.store.root(), rom_search_dirs(app), err);
        if (rom_path.empty()) { SDL_Quit(); return 0; }
    }
    app.m = std::make_unique<Machine>();
    if (!app.m->load_rom(rom_path, &err)) {
        SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_ERROR, "Knuckles' Chaotix Recompiled", err.c_str(), app.window);
        SDL_Quit();
        return 1;
    }
    app.cfg.installed = true;
    app.cfg.rom_sha1 = app.m->rom.sha1;
    app.cfg.rom_path = rom_path;
    if (!app.cfg.save(app.store.config_file()))
        LOGW("setup", "cannot save ROM settings to %s", app.store.config_file().c_str());
    app.m->input.six_button[0] = app.cfg.six_button;
    app.m->input.six_button[1] = app.cfg.six_button;
    warn_about_dead_bindings(app);
    if (!app.autotest_frames || !app.mods_dir.empty()) apply_rom_patches(app);  // autotests are hermetic unless asked
    app.m->reset();
    if (!app.autotest_frames) app.store.load_sram(*app.m);  // autotests are hermetic
    RecompStatus rs = install_recompiled_code(*app.m, app.cfg.use_recompiled && !force_interp);
    LOGI("app", "execution: %s", rs.description.c_str());
    if (!app.autotest_frames || !app.mods_dir.empty()) {  // autotests are hermetic unless asked
        load_mods(app);
    }

    if (app.cfg.achievements) {
        // A file in the user data directory (or beside the executable) wins,
        // so definitions can be edited without rebuilding; otherwise the
        // copy compiled into the binary is used.
        const std::string defs = find_asset(app, "achievements.ini");
        std::string aerr;
        const bool loaded =
            defs.empty()
                ? app.achievements.load_definitions_text(
                      std::string(reinterpret_cast<const char*>(achievements_ini),
                                  achievements_ini_len),
                      &aerr)
                : app.achievements.load_definitions(defs, &aerr);
        if (!loaded) {
            LOGW("achievements", "%s", aerr.c_str());
        } else {
            std::error_code ec;
            std::filesystem::create_directories(app.store.save_dir(), ec);
            app.achievements.load_progress(achievements_progress_path(app));
            app.achievements_on = true;
            LOGI("achievements", "%zu definitions, %d/%d points already earned",
                 app.achievements.list().size(), app.achievements.points_earned(), app.achievements.points_total());
        }
    }
    app.texture = SDL_CreateTexture(app.renderer, SDL_PIXELFORMAT_XRGB8888, SDL_TEXTUREACCESS_STREAMING, kScreenWidth, kScreenHeight);
    SDL_SetTextureScaleMode(app.texture, app.cfg.linear_filter ? SDL_SCALEMODE_LINEAR : SDL_SCALEMODE_NEAREST);
    apply_window_mode(app);
    if (app.cfg.audio && !app.autotest_frames) {
        // The machine produces 16-bit stereo at the YM2612 native rate; SDL
        // resamples to the device. Emulated time drives production, so the
        // audio device never changes game speed.
        SDL_AudioSpec spec{SDL_AUDIO_S16, 2, int(kAudioRate + 0.5)};
        app.audio = SDL_OpenAudioDeviceStream(SDL_AUDIO_DEVICE_DEFAULT_PLAYBACK, &spec, nullptr, nullptr);
        if (app.audio) {
            SDL_SetAudioStreamGain(app.audio, float(app.cfg.volume) / 100.0f);
            SDL_ResumeAudioStreamDevice(app.audio);
            app.m->audio_enabled = true;
        } else {
            LOGW("audio", "cannot open audio device: %s", SDL_GetError());
        }
    }
    // On: always drawn. Auto: only once the screen has actually been touched,
    // so a phone plugged into a controller is not covered in buttons nobody
    // is using. Off: never.
    app.touch_enabled = app.cfg.touch == TouchMode::On;

    const uint64_t freq = SDL_GetPerformanceFrequency();
    const double frame_ticks = double(freq) / kNtscFrameRate;
    uint64_t last = SDL_GetPerformanceCounter();
    double accumulator = 0;
    uint64_t fps_t0 = last, fps_frames = 0, fps_sims = 0;
    uint64_t pass_start = last;
    double worst_pass = 0, worst_emu = 0, worst_present = 0;

    bool menu_was_open = app.menu.open();
    while (app.running) {
        // The menu is where settings change: keep them the moment it closes.
        if (menu_was_open && !app.menu.open()) save_now(app);
        menu_was_open = app.menu.open();
        // Wait before polling input so it is fresh when the frame is run.
        // Rendering an unchanged frame here can block in VSync and leave the
        // next pass catching up by two frames. The original NTSC rate, rather
        // than the monitor refresh rate, remains the simulation clock.
        // Use the previous pass's fast-forward state; a Tab transition takes
        // effect when events are polled below, within at most one game frame.
        uint64_t now = pace_frame(accumulator, last, frame_ticks, freq,
            app.fast_forward || app.autotest_frames != 0,
            [] { return SDL_GetPerformanceCounter(); },
            [](uint64_t ns) { SDL_DelayPrecise(ns); });
        SDL_Event e;
        while (SDL_PollEvent(&e)) {
            switch (e.type) {
            case SDL_EVENT_QUIT: app.running = false; break;
            case SDL_EVENT_KEY_DOWN: handle_key(app, e.key); break;
            case SDL_EVENT_GAMEPAD_BUTTON_DOWN: handle_pad_button(app, e.gbutton.button); break;
            case SDL_EVENT_GAMEPAD_ADDED:
                if (SDL_Gamepad* g = SDL_OpenGamepad(e.gdevice.which)) {
                    app.pads.push_back(g);
                    LOGI("input", "gamepad connected: %s", SDL_GetGamepadName(g));
                }
                break;
            case SDL_EVENT_GAMEPAD_REMOVED:
                for (size_t i = 0; i < app.pads.size(); ++i)
                    if (SDL_GetGamepadID(app.pads[i]) == e.gdevice.which) { SDL_CloseGamepad(app.pads[i]); app.pads.erase(app.pads.begin() + long(i)); break; }
                break;
            case SDL_EVENT_FINGER_DOWN: case SDL_EVENT_FINGER_MOTION: {
                app.touch_enabled = app.cfg.touch != TouchMode::Off;
                int w = 0, h = 0;
                SDL_GetRenderOutputSize(app.renderer, &w, &h);
                const float tx = e.tfinger.x * float(w), ty = e.tfinger.y * float(h);
                if (app.menu.open()) {
                    if (e.type == SDL_EVENT_FINGER_DOWN) app.menu.on_touch_down(tx, ty);
                    break;
                }
                if (e.type == SDL_EVENT_FINGER_DOWN && app.achievements_on) {
                    const SDL_FRect& r = app.achievement_tap;
                    if (r.w > 0 && tx >= r.x && tx <= r.x + r.w && ty >= r.y && ty <= r.y + r.h) {
                        app.menu.show_achievements();
                        break;
                    }
                }
                app.fingers[e.tfinger.fingerID] =
                    app.touch.finger(uint64_t(e.tfinger.fingerID), tx, ty, e.type == SDL_EVENT_FINGER_DOWN);
                break;
            }
            case SDL_EVENT_FINGER_UP: case SDL_EVENT_FINGER_CANCELED:
                if (app.menu.open()) { app.menu.on_touch_up(); break; }
                app.fingers.erase(e.tfinger.fingerID);
                app.touch.lift(uint64_t(e.tfinger.fingerID));
                break;
            case SDL_EVENT_WINDOW_FOCUS_LOST: case SDL_EVENT_WILL_ENTER_BACKGROUND:
            case SDL_EVENT_DID_ENTER_BACKGROUND: case SDL_EVENT_TERMINATING:
                save_now(app);
                break;
            case SDL_EVENT_DID_ENTER_FOREGROUND:
                // Back from the system's storage access page, perhaps.
                if (!app.autotest_frames || !app.mods_dir.empty()) load_mods(app);
                break;
            default: break;
            }
        }
        const bool* ks = SDL_GetKeyboardState(nullptr);
        app.fast_forward = ks[SDL_SCANCODE_TAB];

        // Unified input: keyboard | gamepads | touch -> InputState. While the
        // menu is open it takes the controls, so driving it does not also move
        // the character.
        uint16_t touch_held = 0;
        for (const auto& [id, b] : app.fingers) touch_held |= b;
        uint16_t raw = 0, raw2 = 0;
        // Emulated frames advance in batches, so a window of frame numbers can
        // be stepped straight over: arm on reaching the frame, then hold for a
        // number of passes round this loop.
        for (auto& h : app.host_script) {
            if (!h.armed && app.m->frame_count >= h.frame) { h.armed = true; h.remaining = int(h.frame ? h.remaining : h.remaining); }
            if (h.armed && h.remaining > 0) { raw |= h.buttons; --h.remaining; }
        }
        if (!app.menu.open()) {
            // Touch belongs to player 1; the on-screen pad has no second set.
            raw |= device_buttons(app, 0) | touch_held;
            raw2 = device_buttons(app, 1);
        }
        uint16_t buttons = raw;
        app.prev_buttons = raw;
        if (app.inject_start > 0) { buttons |= PAD_START; --app.inject_start; }
        app.m->input.pad[0] = buttons;
        app.m->input.pad[1] = raw2;

        {
            // True widescreen margins follow the display aspect (levels only;
            // see runtime/patches.h). Resizing the window takes effect at
            // once; turning widescreen off and on again waits for the next
            // level load, because the ring shift is latched there.
            int ww = 0, wh = 0;
            SDL_GetRenderOutputSize(app.renderer, &ww, &wh);
            const double fa = aspect_value(app.cfg.viewport.aspect, app.cfg.viewport.custom_aspect, wh > 0 ? double(ww) / double(wh) : 0.0);
            app.m->wide_enabled = app.cfg.widescreen;
            app.m->wide_everywhere = app.cfg.wide_everywhere;
            app.m->wide_hud_edges = app.cfg.wide_hud;
            app.m->wide_extra = app.cfg.widescreen ? widescreen_extra(fa, patches::kMaxWideExtra) : 0;
            // A frame taller than 4:3 gets extra rows below instead.
            app.m->wide_extra_bottom = app.cfg.widescreen ? widescreen_rows(fa, patches::kMaxWideExtraBottom) : 0;
        }
        if (app.cli_stage_frame && app.m->frame_count >= app.cli_stage_frame && app.start_stage) {
            app.cli_stage_frame = 0;
            app.menu.close();
            app.start_stage(app.cli_stage);
        }
        int steps = 0;
        const int max_steps = app.fast_forward ? 8 : 3;
        uint64_t emu_t0 = SDL_GetPerformanceCounter();
        const bool autotest = app.autotest_frames != 0;
        // With scripted host input the loop runs one emulated frame per pass,
        // so a "hold for N frames" means N frames rather than N batches of up
        // to 64 - the difference between a tap and holding the button down.
        const int autotest_batch = app.host_script.empty() ? 64 : 1;
        while ((accumulator >= frame_ticks || app.fast_forward || autotest) &&
               steps < (autotest ? autotest_batch : max_steps)) {
            if (autotest && app.m->frame_count >= app.autotest_frames) break;
            // Scripted keys are pushed as events and handled on the next pass
            // round the event loop, exactly like a key someone pressed.
            for (auto& k : app.key_script) {
                if (k.done || app.m->frame_count < k.frame) continue;
                k.done = true;
                SDL_Event ke{};
                ke.type = SDL_EVENT_KEY_DOWN;
                ke.key.key = k.key;
                ke.key.down = true;
                ke.key.repeat = false;
                SDL_PushEvent(&ke);
            }
            // Scripted input is applied per emulated frame (deterministic).
            uint16_t scripted = 0;
            for (const auto& p : app.script)
                if (app.m->frame_count >= p.frame && app.m->frame_count < p.frame + p.duration) scripted |= p.buttons;
            // And so are the taps of Start that carry a waiting stage request
            // through the title screen: counted in emulated frames, or a pass
            // that simulates several would stretch a tap into a hold.
            scripted |= stage_kick_button(app);
            app.m->input.pad[0] = uint16_t(buttons | scripted);
            app.recorded.push_back(uint32_t(uint16_t(buttons | scripted)) | uint32_t(raw2) << 16);
            app.m->input.pad[1] = raw2;
            apply_cheats(app);
            audio::set_music_and_effect_levels(*app.m, float(app.cfg.music_volume) / 100.0f,
                                               float(app.cfg.effects_volume) / 100.0f);
            const size_t first_sample = app.m->audio_out.size();
            app.m->run_frame();
            // Replacement music is music too.
            app.music.set_volume(app.cfg.mod_music_volume * app.cfg.music_volume / 100);
            app.music.after_frame(*app.m, first_sample);
            follow_time_attack(app);
            if (app.achievements_on && !app.cheating) {
                app.achievements.update(*app.m, [&](const achievements::Achievement& a) {
                    app.toasts.push_back({a.title, a.description, SDL_GetTicks() + 5000});
                    app.achievements.save_progress(achievements_progress_path(app));
                });
            }
            if (!app.fast_forward) accumulator -= frame_ticks;
            ++steps;
        }
        if (app.fast_forward) accumulator = 0;
        if (app.m->vdp.tiles != app.tiles) app.m->vdp.tiles = app.tiles;
        if (TileReplacer* t = app.tiles.get()) {
            t->dumping = app.cfg.dump_tiles;
            if (const int n = write_tile_dumps(*t, app.tiles_dir + "/Dump")) LOGI("tiles", "%d tile(s) dumped", n);
        }
        uint64_t emu_t1 = SDL_GetPerformanceCounter();
        if (steps) app.timing.emu_ms = double(emu_t1 - emu_t0) * 1000.0 / double(freq) / steps;
        fps_sims += uint64_t(steps);

        // Audio: hand over what the machine produced; keep ~50 ms queued with a
        // gentle rate adjustment instead of dropping or stretching audio.
        if (app.audio) {
            // VOLUME takes effect at once, not at the next start.
            SDL_SetAudioStreamGain(app.audio, float(app.cfg.volume) / 100.0f);
            if (!app.m->audio_out.empty()) {
                if (app.fast_forward) app.m->audio_out.clear();
                else {
                    SDL_PutAudioStreamData(app.audio, app.m->audio_out.data(), int(app.m->audio_out.size() * sizeof(int16_t)));
                    app.m->audio_out.clear();
                }
            }
            const double target = kAudioRate * 0.05 * 4;  // bytes queued for 50 ms (stereo s16)
            double queued = double(SDL_GetAudioStreamQueued(app.audio));
            double err = (queued - target) / target;
            float ratio = float(1.0 + std::clamp(err * 0.01, -0.01, 0.01));
            SDL_SetAudioStreamFrequencyRatio(app.audio, ratio);
            if (queued > target * 6) SDL_ClearAudioStream(app.audio);  // after a stall
        } else {
            app.m->audio_out.clear();
        }

        // SRAM autosave shortly after the game writes it.
        if (app.m->sram_dirty && !app.autotest_frames) {
            if (!app.sram_dirty_since) app.sram_dirty_since = now;
            else if (double(now - app.sram_dirty_since) / double(freq) > 1.0) { app.store.store_sram(*app.m); app.sram_dirty_since = 0; }
        }

        // Present
        uint64_t pr_t0 = SDL_GetPerformanceCounter();
        int ow = 0, oh = 0;
        SDL_GetRenderOutputSize(app.renderer, &ow, &oh);
        SDL_SetRenderDrawColor(app.renderer, 0, 0, 0, 255);
        SDL_RenderClear(app.renderer);
        SDL_UpdateTexture(app.texture, nullptr, app.m->framebuffer, kScreenWidth * 4);
        app.cfg.viewport.image_aspect = image_aspect_for_size(app.m->fb_width, app.m->fb_width - 2 * app.m->fb_extra,
                                                              app.m->fb_height, app.m->fb_height - app.m->fb_extra_bottom);
        ViewportResult vp = compute_viewport(app.cfg.viewport, ow, oh, app.m->fb_width, app.m->fb_height);
        SDL_FRect src{0, 0, float(app.m->fb_width), float(app.m->fb_height)};
        SDL_FRect dst{float(vp.image.x), float(vp.image.y), float(vp.image.w), float(vp.image.h)};
        // The front end puts the game's own picture beside its list instead of
        // behind it, and says where.
        SDL_FRect art{};
        bool panelled = false;
        if (app.ui.ready()) {
            app.ui.begin_frame();
            panelled = app.menu.art_panel(app.ui, &art);
        }
        // With a panel the picture is drawn twice: once filling the window as
        // a backdrop, which the menu then dims, and once in the panel itself.
        SDL_RenderTexture(app.renderer, app.texture, &src, &dst);
        if (panelled) {
            app.menu.draw_backdrop_dim(app.ui);
            SDL_RenderTexture(app.renderer, app.texture, &src, &art);
        }
        if (app.touch_enabled) {
            app.touch.layout(ow, oh, app.cfg.touch_stick, app.cfg.touch_sonic_cd);
            draw_touch_controls(app, touch_held);
        }
        if (app.ui.ready()) {
            app.menu.draw(app.ui, app.achievements);
            if (app.achievements_on) draw_toasts(app);
            app.ui.end_frame();
        }
        if (app.cfg.debug_overlay) {
            const SDL_DisplayMode* dm = SDL_GetCurrentDisplayMode(SDL_GetDisplayForWindow(app.window));
            app.timing.refresh_hz = dm ? unsigned(dm->refresh_rate + 0.5f) : 0;
            app.timing.fast_forward = app.fast_forward;
            char vline[200];
            std::snprintf(vline, sizeof vline, "video: %dx%d out, image %.0fx%.0f, aspect %s, %s, %s, %s, wide %d+%d%s", ow, oh, vp.image.w, vp.image.h,
                          aspect_name(app.cfg.viewport.aspect), scale_name(app.cfg.viewport.scale),
                          app.cfg.linear_filter ? "linear" : "nearest", window_mode_name(app.cfg.window_mode),
                          app.m->fb_extra, app.m->fb_extra_bottom, app.m->wide_active ? " (active)" : "");
            auto lines = build_debug_overlay(*app.m, app.timing, app.overlay_page, vline, app.watches);
            float scale = std::max(1.0f, float(oh) / 540.0f);
            SDL_SetRenderScale(app.renderer, scale, scale);
            SDL_SetRenderDrawBlendMode(app.renderer, SDL_BLENDMODE_BLEND);
            SDL_SetRenderDrawColor(app.renderer, 0, 0, 0, 170);
            SDL_FRect bg{0, 0, 8.0f * 100, 10.0f * float(lines.size()) + 4};
            SDL_RenderFillRect(app.renderer, &bg);
            SDL_SetRenderDrawColor(app.renderer, 255, 255, 160, 255);
            for (size_t i = 0; i < lines.size(); ++i) SDL_RenderDebugText(app.renderer, 4, 4 + 10.0f * float(i), lines[i].c_str());
            SDL_SetRenderScale(app.renderer, 1, 1);
        }
        if (app.autotest_frames && app.m->frame_count >= app.autotest_frames) {
            if (!app.autotest_shot.empty()) capture_output(app);
            app.running = false;
        }
        // Emulated frames advance in batches, so fire on "reached" rather
        // than "equals" or the moment is stepped straight over.
        for (auto& shot : app.extra_shots) {
            if (shot.done || app.m->frame_count < shot.frame) continue;
            shot.done = true;
            const std::string keep = app.autotest_shot;
            app.autotest_shot = shot.path;
            capture_output(app);
            app.autotest_shot = keep;
        }
        SDL_RenderPresent(app.renderer);
        app.timing.present_ms = double(SDL_GetPerformanceCounter() - pr_t0) * 1000.0 / double(freq);
        ++fps_frames;
        {
            const uint64_t pass_end = SDL_GetPerformanceCounter();
            worst_pass = std::max(worst_pass, double(pass_end - pass_start) * 1000.0 / double(freq));
            worst_emu = std::max(worst_emu, app.timing.emu_ms * steps);
            worst_present = std::max(worst_present, app.timing.present_ms);
            pass_start = pass_end;
        }
        if (now - fps_t0 > freq) {
            double s = double(now - fps_t0) / double(freq);
            app.timing.render_fps = double(fps_frames) / s;
            app.timing.sim_fps = double(fps_sims) / s;
            if (app.log_timing)
                LOGI("timing", "frame %llu: %.1f presented/s, %.1f emulated/s, slowest pass %.1f ms (emulation %.1f, present %.1f)",
                     (unsigned long long)app.m->frame_count, app.timing.render_fps, app.timing.sim_fps, worst_pass,
                     worst_emu, worst_present);
            worst_pass = worst_emu = worst_present = 0;
            fps_frames = fps_sims = 0;
            fps_t0 = now;
        }
    }

    if (!app.autotest_frames) {
        if (app.m->sram_dirty) app.store.store_sram(*app.m);
        app.cfg.save(app.store.config_file());
    }
    if (!app.record_path.empty()) write_recording(app, app.record_path);
    if (app.audio) SDL_DestroyAudioStream(app.audio);
    for (SDL_Gamepad* g : app.pads) SDL_CloseGamepad(g);
    SDL_DestroyTexture(app.texture);
    SDL_DestroyRenderer(app.renderer);
    SDL_DestroyWindow(app.window);
    SDL_Quit();
    return 0;
}
