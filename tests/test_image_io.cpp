std::string temp_path(const char* name) {
    return (std::filesystem::temp_directory_path() / name).string();
}

uint32_t crc32(const uint8_t* d, size_t n) {
    uint32_t c = 0xFFFFFFFFu;
    for (size_t i = 0; i < n; ++i) {
        c ^= d[i];
        for (int k = 0; k < 8; ++k) c = (c & 1) ? 0xEDB88320u ^ (c >> 1) : c >> 1;
    }
    return ~c;
}

uint32_t get32(const uint8_t* p) { return uint32_t(p[0]) << 24 | uint32_t(p[1]) << 16 | uint32_t(p[2]) << 8 | p[3]; }

// Recomputes every chunk's CRC, so a test can change a chunk's contents and
// reach the code past the CRC check.
void resign(std::vector<uint8_t>& png) {
    size_t pos = 8;
    while (pos + 12 <= png.size()) {
        const uint32_t len = get32(&png[pos]);
        if (len > png.size() - pos - 12) return;
        const uint32_t c = crc32(&png[pos + 4], len + 4);
        uint8_t* out = &png[pos + 8 + len];
        out[0] = uint8_t(c >> 24); out[1] = uint8_t(c >> 16); out[2] = uint8_t(c >> 8); out[3] = uint8_t(c);
        pos += len + 12;
    }
}

template <size_t N> std::vector<uint8_t> bytes(const uint8_t (&a)[N]) { return std::vector<uint8_t>(a, a + N); }

