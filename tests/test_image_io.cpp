TEST(image_io, indexed_png_round_trips_indices_palette_and_alpha) {
    uint32_t palette[16];
    for (int i = 0; i < 16; ++i) palette[i] = 0xFF000000u | uint32_t(i * 0x101010);
    palette[0] = 0x00000000u;   // the transparent colour every tile has
    palette[5] = 0x80FF8040u;   // and a translucent one, in the middle
    uint8_t tile[64];
    for (int i = 0; i < 64; ++i) tile[i] = uint8_t((i % 8 + (i / 8) * 3) % 16);
    const std::string path = temp_path("chaotix_test_indexed.png");
    CHECK(write_png_indexed(path, tile, 8, 8, palette, 16));

    PngImage img;
    std::string err;
    CHECK(read_png(path, img, &err));
    CHECK_EQ(img.width, 8);
    CHECK_EQ(img.height, 8);
    CHECK(img.indexed);
    CHECK_EQ(img.palette.size(), size_t(16));
    CHECK_EQ(img.indices.size(), size_t(64));
    CHECK_EQ(img.argb.size(), size_t(64));
    for (int i = 0; i < 16 && i < int(img.palette.size()); ++i) CHECK_EQ(img.palette[size_t(i)], palette[i]);
    for (size_t i = 0; i < 64 && i < img.indices.size() && i < img.argb.size(); ++i) {
        CHECK_EQ(img.indices[i], tile[i]);
        CHECK_EQ(img.argb[i], palette[tile[i]]);
    }

    // An opaque palette needs no tRNS, and reads back opaque.
    for (uint32_t& c : palette) c |= 0xFF000000u;
    CHECK(write_png_indexed(path, tile, 8, 8, palette, 16));
    CHECK(read_png(path, img, &err));
    for (uint32_t c : img.palette) CHECK_EQ(c >> 24, 0xFFu);

    // Indices past the palette are refused rather than written.
    tile[9] = 16;
    CHECK(!write_png_indexed(path, tile, 8, 8, palette, 16));
    std::remove(path.c_str());
}

TEST(image_io, truecolor_png_round_trips) {
    uint32_t px[7 * 5];
    for (int i = 0; i < 7 * 5; ++i) px[i] = uint32_t(i) * 0x0705030Bu;
    const std::string path = temp_path("chaotix_test_rgb.png");
    CHECK(write_png(path, px, 7, 5, 7));
    PngImage img;
    std::string err;
    CHECK(read_png(path, img, &err));
    CHECK_EQ(img.width, 7);
    CHECK_EQ(img.height, 5);
    CHECK(!img.indexed);
    CHECK_EQ(img.argb.size(), size_t(35));
    for (size_t i = 0; i < 35 && i < img.argb.size(); ++i) CHECK_EQ(img.argb[i], 0xFF000000u | (px[i] & 0xFFFFFF));
    std::remove(path.c_str());

    CHECK(!read_png(temp_path("chaotix_test_no_such_file.png"), img, &err));
    CHECK(!err.empty());
}

TEST(image_io, decodes_rgba_with_every_filter_and_dynamic_huffman) {
    PngImage img;
    std::string err;
    CHECK(decode_png(kRgbaAllFilters, sizeof kRgbaAllFilters, img, &err));
    CHECK_EQ(img.width, 8);
    CHECK_EQ(img.height, 10);
    CHECK(!img.indexed);
    if (img.argb.size() != 80) return;
    for (uint32_t y = 0; y < 10; ++y)
        for (uint32_t x = 0; x < 8; ++x) {
            const uint32_t r = (x * 30 + y) & 255, g = (y * 20) & 255, b = (x * y * 7) & 255, a = (255 - x * 10 - y * 3) & 255;
            CHECK_EQ(img.argb[y * 8 + x], a << 24 | r << 16 | g << 8 | b);
        }
}

